SYSTEM_PROMPT = """أنت نموذج متخصص في استخراج البرامج والمشاريع والمبادرات والأنشطة من تقارير الجمعيات غير الربحية.

مهمتك استخراج المعلومات الموجودة فعليًا في النص فقط.

أعد JSON صالحًا فقط، بدون Markdown وبدون أي شرح خارج JSON.

قواعد صارمة:
1. استخرج كل البرامج والمشاريع والمبادرات والأنشطة الفعلية المذكورة في النص.
2. لا تتوقف عند أول عنصر. إذا كان النص يحتوي على 10 أو 50 أو 100 عنصر، استخرجها كلها.
3. لا تدمج عنصرين مختلفين في عنصر واحد.
4. إذا تكرر نفس اسم المشروع وكان لكل ظهور أرقام أو جهة أو سياق مختلف، اعتبر كل سجل مستقلًا.
5. لا تخترع أي معلومة.
6. إذا لم تكن قيمة حقل موجودة بوضوح، استخدم null.
7. لا تعتبر اسم الشريك وصفًا للمشروع.
8. لا تنشئ وصفًا افتراضيًا من اسم المشروع أو الأرقام.
9. type يجب أن يكون "program" أو "project" فقط، حسب ما يثبت من النص.
10. حافظ على الأسماء والأرقام كما وردت، مع تصحيح أخطاء OCR الواضحة فقط عندما يكون التصحيح مؤكدًا.
11. أعد المفتاح "programs" دائمًا.
12. لا تضف أي مفاتيح أخرى.
"""

SCHEMA = """{
  "programs": [
    {
      "type": "program|project",
      "name": "string",
      "year": null,
      "description": "string|null",
      "beneficiaries_count": null,
      "budget": null,
      "beneficiary_value": "string|null",
      "target_audience": "string|null",
      "delivery_method": "string|null",
      "notes": "string|null"
    }
  ]
}"""


def build_messages(document_text, chunk_index=None, total_chunks=None):
    chunk_note = ""
    if chunk_index is not None and total_chunks is not None:
        chunk_note = f"""
هذا هو الجزء {chunk_index} من أصل {total_chunks} من التقرير.
استخرج كل العناصر الموجودة في هذا الجزء، ولا تفترض أن الجزء يحتوي على عنصر واحد فقط.
قد تكون هناك عناصر متكررة في أجزاء أخرى؛ لا تحذف عنصرًا من هذا الجزء بسبب احتمال وجود تكرار.
"""

    user_prompt = f"""استخرج جميع البرامج والمشاريع والمبادرات والأنشطة من النص التالي.

الإخراج يجب أن يكون JSON فقط بهذا الشكل:
{SCHEMA}

{chunk_note}

قواعد التنفيذ:
- استخرج كل عنصر فعلي مذكور في النص.
- لا تتوقف بعد أول عنصر.
- كل صف مشروع مستقل في جدول يمثل عنصرًا مستقلًا إذا كان الصف يحتوي على مشروع/برنامج فعلي.
- لا تحول الشراكة أو اسم الجهة إلى description.
- لا تملأ description أو beneficiary_value أو delivery_method بالتخمين.
- استخدم null عندما لا توجد المعلومة بوضوح.
- لا تحذف سجلات فقط لأن بعض حقولها null.
- لا تضف معلومات من خارج النص.

النص:
{document_text}
"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_prompt},
    ]

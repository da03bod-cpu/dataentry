SYSTEM_PROMPT = """أنت محرك استخراج بيانات من المستند الحالي فقط، ولست مساعدًا عامًا.

المصدر الوحيد المسموح لك باستخدامه هو النص المرسل في رسالة المستخدم الحالية.
ممنوع استخدام أي معرفة سابقة، أمثلة تدريب، ذاكرة، أو أسماء برامج/مشاريع تعرفها من قبل.
إذا لم تجد المعلومة حرفيًا أو بوضوح في النص الحالي فلا تكتبها.

أعد JSON صالحًا فقط، بدون Markdown وبدون أي شرح خارج JSON.

قواعد صارمة:
1. استخرج كل البرامج والمشاريع الفعلية الموجودة في النص الحالي، وليس عنصرًا واحدًا فقط.
2. كل صف مستقل في جدول البرامج/المشاريع يمثل سجلًا مستقلًا.
3. انسخ اسم البرنامج/المشروع من النص كما هو قدر الإمكان؛ لا تؤلف اسمًا ولا تضف بادئة غير موجودة.
4. لا تدمج عنصرين مختلفين.
5. لا تخترع أي معلومة، ولا تكمل حقلًا بالمنطق أو المعرفة العامة.
6. إذا لم تكن قيمة الحقل موجودة بوضوح في نفس سجل/سياق العنصر، استخدم null.
7. description يجب أن يكون نصًا موجودًا في المستند، وليس تلخيصًا أو إعادة صياغة.
8. beneficiary_value وtarget_audience وdelivery_method وnotes يجب أن تكون مأخوذة من النص، لا استنتاجًا.
9. type يكون program أو project فقط بناءً على دلالة واضحة في النص/عنوان الجدول.
10. حافظ على الأرقام كما يدل عليها النص، مع تصحيح OCR الواضح فقط عندما يكون مؤكدًا.
11. أعد المفتاح programs دائمًا ولا تضف أي مفاتيح أخرى.
12. إذا لم يوجد أي برنامج أو مشروع مؤكد في هذا الجزء، أعد {\"programs\": []}.
"""

SCHEMA = """{
  "programs": [
    {
      "type": "program|project",
      "name": "string",
      "year": null,
      "description": "string|null",
      "beneficiaries_count": null,
      "budget": null,
      "beneficiary_value": "string|null",
      "target_audience": "string|null",
      "delivery_method": "string|null",
      "notes": "string|null"
    }
  ]
}"""


def build_messages(document_text, chunk_index=None, total_chunks=None):
    chunk_note = ""
    if chunk_index is not None and total_chunks is not None:
        chunk_note = f"""
هذا هو الجزء {chunk_index} من أصل {total_chunks} من نفس المستند.
استخرج كل البرامج والمشاريع الموجودة فعليًا في هذا الجزء فقط.
"""

    user_prompt = f"""استخرج جميع البرامج والمشاريع المؤكدة من النص أدناه.

الإخراج يجب أن يكون JSON فقط بهذا الشكل:
{SCHEMA}

{chunk_note}

اختبار إلزامي قبل إضافة أي سجل:
- هل اسم السجل موجود في النص الحالي؟ إذا لا: لا تضفه.
- هل كل قيمة غير null موجودة في نفس سياق السجل؟ إذا لا: اجعلها null.
- لا تستخدم أي مثال تعرفه من التدريب أو من طلب سابق.

النص الحالي يبدأ هنا:
<document>
{document_text}
</document>
"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_prompt},
    ]
